export function rdpScancodeFromEvent(e: KeyboardEvent): {
  scancode: number
  extended: boolean
} | null {
  const raw = KEY_MAP[e.code]
  if (raw == null) return null
  const extended = (raw & 0xe000) === 0xe000 || raw > 0xff
  const scancode = raw & 0xff
  return { scancode, extended }
}
